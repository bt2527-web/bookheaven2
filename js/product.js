// ==========================================
// БЕЗПЕЧНЕ ВІДОБРАЖЕННЯ ТЕКСТУ
// ==========================================

function productSafeText(value) {
    return String(value ?? "").replace(/[&<>"']/g, function(char) {
        const symbols = {
            "&": "&amp;",
            "<": "&lt;",
            ">": "&gt;",
            '"': "&quot;",
            "'": "&#039;"
        };

        return symbols[char];
    });
}


// ==========================================
// ВІДГУКИ
// ==========================================

function getReviewKey(productId) {
    return "bookspace-reviews-" + productId;
}

function getBookReviews(productId) {
    try {
        const saved = localStorage.getItem(getReviewKey(productId));
        const reviews = JSON.parse(saved || "[]");

        return Array.isArray(reviews) ? reviews : [];
    } catch (error) {
        console.error("Помилка читання відгуків:", error);
        return [];
    }
}

function renderReviews(productId) {
    const container = document.getElementById("reviews-list");

    if (!container) return;

    const reviews = getBookReviews(productId);

    if (reviews.length === 0) {
        container.innerHTML = `
            <p class="empty-message">
                Відгуків поки немає. Будь першим, хто поділиться враженнями!
            </p>
        `;
        return;
    }

    container.innerHTML = reviews.map(function(review) {
        const rating = Math.max(
            1,
            Math.min(5, Number(review.rating) || 5)
        );

        return `
            <article class="review-card">
                <div class="review-card-header">
                    <strong>${productSafeText(review.name)}</strong>

                    <span class="review-stars">
                        ${"★".repeat(rating)}${"☆".repeat(5 - rating)}
                    </span>
                </div>

                <p>${productSafeText(review.text)}</p>

                <span class="review-date">
                    ${productSafeText(review.date)}
                </span>
            </article>
        `;
    }).join("");
}


